/* প্রোডাকশন গ্রেড কোডে অনেক সময় আমাদের ডাটার জন্য অপেক্ষা করতে হয়। সেক্ষেত্রে আমরা Async/Await ব্যবহার করি। await ব্যবহারের ফলে কোডটি দেখতে সিঙ্ক্রোনাস কোডের মতো মনে হলেও এটি আসলে নন-ব্লকিংভাবেই কাজ করছে। জাভাস্ক্রিপ্ট যখন await দেখে, তখন সে পুরো ব্রাউজার বা সার্ভারকে "ফ্রিজ" করে দেয় না। বরং সে শুধু ওই নির্দিষ্ট ফাংশনটির এক্সিকিউশন "পজ" (Pause) করে রাখে এবং মেইন থ্রেডকে অন্য কাজ করার জন্য ছেড়ে দেয়। সহজ কথায়, আপনি await ব্যবহার করে জাভাস্ক্রিপ্টকে বলছেন: "ভাই, তুমি ব্যাকগ্রাউন্ডে ডাটাটা নিয়ে আসো, কিন্তু এই ফাংশনের ভেতরে এর পরের লাইনে যেও না যতক্ষণ না ডাটাটা হাতে পাচ্ছ।" */

/* যখন জাভাস্ক্রিপ্ট await fetch(...) লাইনটিতে পৌঁছায়:

সে fetch অপারেশনটিকে Web APIs (ব্রাউজারের ক্ষেত্রে) বা C++ APIs (Node.js-এর ক্ষেত্রে) এর কাছে পাঠিয়ে দেয়।

জাভাস্ক্রিপ্ট ওই ফাংশন থেকে সাময়িকভাবে বের হয়ে আসে এবং Call Stack খালি করে দেয়।

মেইন থ্রেড এখন ফ্রি! সে যদি অন্য কোনো বাটন ক্লিক বা অন্য কোনো ফাংশন কল পায়, তবে সেগুলো প্রসেস করতে থাকে।

যখন নেটওয়ার্ক থেকে ডাটা চলে আসে, তখন সেই রেসপন্সটি Microtask Queue-তে জমা হয়।

ইভেন্ট লুপ যখন দেখে যে মেইন থ্রেড (Call Stack) একদম ফ্রি, তখন সে ওই পজ হওয়া ফাংশনটিকে আবার স্ট্যাকে তুলে আনে এবং await-এর পরের লাইন থেকে কাজ শুরু করে। */

/* কেন আমরা একে "সিনক" করার চেষ্টা করি? (A Practical Example)
অনেক সময় আমাদের ডাটা ছাড়া পরবর্তী কাজ করা অসম্ভব হয়ে পড়ে। ধরুন, আপনি একটি ইউজারের প্রোফাইল দেখাচ্ছেন। আগে তো ইউজার ডাটা লাগবে, তারপর না আপনি নাম প্রিন্ট করবেন! */

const loadData = async () => {
  try {
    console.log("First");
    console.log("Second");

    const res = await fetch("https://jsonplaceholder.typicode.com/todos/1");
    const data = await res.json();
    console.log(data);

    console.log("Third");
    console.log("Fourth");
  } catch {
    console.log("Error");
  }
};

loadData();
